-- Limpieza (permite re-ejecutar el script desde cero)
DROP TABLE IF EXISTS rendimiento, transaccion, precio_historico, trm,
                     tes, cdt, accion_fondo, activo, tipo_activo,
                     movimiento_efectivo, cuenta, cliente, asesor,
                     perfil_riesgo CASCADE;

-- ---------------------------------------------------------------------
-- PERFIL_RIESGO (catalogo)                                   Reglas 1, 2
-- limite_max_renta_var: % maximo del portafolio en acciones y fondos.
-- El perfil agresivo usa 100 (sin limite) en lugar de NULL.
-- ---------------------------------------------------------------------
CREATE TABLE perfil_riesgo (
    id_perfil            SMALLINT      PRIMARY KEY,
    nombre_perfil        VARCHAR(20)   NOT NULL UNIQUE
        CHECK (nombre_perfil IN ('CONSERVADOR', 'MODERADO', 'AGRESIVO')),
    limite_max_renta_var NUMERIC(5,2)  NOT NULL
        CHECK (limite_max_renta_var BETWEEN 0 AND 100)
);

-- ---------------------------------------------------------------------
-- ASESOR                                                        Regla 3
-- Claves candidatas: (tipo_documento, numero_documento) y email.
-- ---------------------------------------------------------------------
CREATE TABLE asesor (
    id_asesor        INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_documento   VARCHAR(3)    NOT NULL DEFAULT 'CC'
        CHECK (tipo_documento IN ('CC', 'CE', 'PA')),
    numero_documento VARCHAR(20)   NOT NULL,
    nombres          VARCHAR(100)  NOT NULL,
    apellidos        VARCHAR(100)  NOT NULL,
    email            VARCHAR(150)  NOT NULL UNIQUE
        CHECK (email LIKE '%_@_%._%'),
    telefono         VARCHAR(20),
    fecha_ingreso    DATE          NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT uq_asesor_documento UNIQUE (tipo_documento, numero_documento)
);

-- ---------------------------------------------------------------------
-- CLIENTE                                                    Reglas 1, 3
-- Un unico perfil y un unico asesor (FK NOT NULL = participacion total).
-- ---------------------------------------------------------------------
CREATE TABLE cliente (
    id_cliente        INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_perfil         SMALLINT      NOT NULL REFERENCES perfil_riesgo (id_perfil),
    id_asesor         INTEGER       NOT NULL REFERENCES asesor (id_asesor),
    tipo_documento    VARCHAR(3)    NOT NULL DEFAULT 'CC'
        CHECK (tipo_documento IN ('CC', 'CE', 'PA')),
    numero_documento  VARCHAR(20)   NOT NULL,
    nombres           VARCHAR(100)  NOT NULL,
    apellidos         VARCHAR(100)  NOT NULL,
    email             VARCHAR(150)  NOT NULL UNIQUE
        CHECK (email LIKE '%_@_%._%'),
    telefono          VARCHAR(20),
    fecha_nacimiento  DATE          NOT NULL,
    fecha_vinculacion DATE          NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT uq_cliente_documento UNIQUE (tipo_documento, numero_documento),
    -- Solo personas naturales mayores de edad al vincularse
    CONSTRAINT ck_cliente_mayor_edad
        CHECK (fecha_vinculacion >= fecha_nacimiento + INTERVAL '18 years')
);

-- ---------------------------------------------------------------------
-- CUENTA (portafolio)                                       Reglas 4, 10
-- saldo_efectivo (USD) es una REDUNDANCIA CONTROLADA: se puede derivar
-- de movimientos, transacciones y rendimientos, pero se almacena para
-- validar compras con bloqueo de fila (SELECT ... FOR UPDATE).
-- Solo lo modifican los triggers (ver 02_funciones_triggers.sql).
-- ---------------------------------------------------------------------
CREATE TABLE cuenta (
    id_cuenta      INTEGER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente     INTEGER        NOT NULL REFERENCES cliente (id_cliente),
    nombre_cuenta  VARCHAR(100)   NOT NULL,
    fecha_apertura DATE           NOT NULL DEFAULT CURRENT_DATE,
    saldo_efectivo NUMERIC(15,2)  NOT NULL DEFAULT 0
        CHECK (saldo_efectivo >= 0),                 -- Regla 4: sin credito
    estado         VARCHAR(10)    NOT NULL DEFAULT 'ACTIVA'
        CHECK (estado IN ('ACTIVA', 'INACTIVA', 'CERRADA')),
    CONSTRAINT uq_cuenta_nombre UNIQUE (id_cliente, nombre_cuenta)
);

-- ---------------------------------------------------------------------
-- MOVIMIENTO_EFECTIVO: depositos y retiros de la cuenta (USD)
-- ---------------------------------------------------------------------
CREATE TABLE movimiento_efectivo (
    id_movimiento   INTEGER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cuenta       INTEGER        NOT NULL REFERENCES cuenta (id_cuenta),
    tipo_movimiento VARCHAR(10)    NOT NULL
        CHECK (tipo_movimiento IN ('DEPOSITO', 'RETIRO')),
    fecha_hora      TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    monto           NUMERIC(15,2)  NOT NULL CHECK (monto > 0)
);

-- ---------------------------------------------------------------------
-- TIPO_ACTIVO (catalogo y discriminador de la especializacion) Regla 12
-- Los id son fijos porque los CHECK de los subtipos dependen de ellos:
--   1 = ACCION, 2 = FONDO, 3 = CDT, 4 = TES
-- clase_activo permite aplicar el limite de renta variable (Regla 2).
-- ---------------------------------------------------------------------
CREATE TABLE tipo_activo (
    id_tipo_activo SMALLINT     PRIMARY KEY CHECK (id_tipo_activo BETWEEN 1 AND 4),
    nombre_tipo    VARCHAR(20)  NOT NULL UNIQUE
        CHECK (nombre_tipo IN ('ACCION', 'FONDO', 'CDT', 'TES')),
    clase_activo   VARCHAR(15)  NOT NULL
        CHECK (clase_activo IN ('RENTA_VARIABLE', 'RENTA_FIJA'))
);

-- ---------------------------------------------------------------------
-- ACTIVO (supertipo)                                           Regla 12
-- UNIQUE (id_activo, id_tipo_activo) existe solo para que los subtipos
-- puedan referenciar el par y asi garantizar la especializacion DISJUNTA.
-- ---------------------------------------------------------------------
CREATE TABLE activo (
    id_activo      INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tipo_activo SMALLINT      NOT NULL REFERENCES tipo_activo (id_tipo_activo),
    nombre         VARCHAR(150)  NOT NULL UNIQUE,
    fecha_registro DATE          NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT uq_activo_tipo UNIQUE (id_activo, id_tipo_activo)
);

-- ---------------------------------------------------------------------
-- Subtipos de ACTIVO. Especializacion disjunta y total:
--  * Disjunta: FK compuesta (id_activo, id_tipo_activo) + CHECK del tipo.
--    Un activo tipo CDT no puede tener fila en tes ni en accion_fondo.
--  * Total: trigger diferido en 02_funciones_triggers.sql (todo activo
--    debe tener su fila de subtipo al confirmar la transaccion).
-- ---------------------------------------------------------------------

-- ACCION_FONDO: acciones y fondos indexados (cotizan en USD)
CREATE TABLE accion_fondo (
    id_activo      INTEGER      PRIMARY KEY,
    id_tipo_activo SMALLINT     NOT NULL CHECK (id_tipo_activo IN (1, 2)),
    ticker         VARCHAR(10)  NOT NULL UNIQUE,
    mercado        VARCHAR(20)  NOT NULL,
    CONSTRAINT fk_accion_fondo_activo
        FOREIGN KEY (id_activo, id_tipo_activo)
        REFERENCES activo (id_activo, id_tipo_activo)
);

-- CDT: la tasa NO es atributo del CDT sino de la compra (Regla 7),
-- por eso vive en transaccion.tasa_pactada. El plazo se deriva de las
-- fechas y no se almacena.
CREATE TABLE cdt (
    id_activo         INTEGER       PRIMARY KEY,
    id_tipo_activo    SMALLINT      NOT NULL CHECK (id_tipo_activo = 3),
    entidad_emisora   VARCHAR(100)  NOT NULL,
    fecha_emision     DATE          NOT NULL,
    fecha_vencimiento DATE          NOT NULL,
    CONSTRAINT fk_cdt_activo
        FOREIGN KEY (id_activo, id_tipo_activo)
        REFERENCES activo (id_activo, id_tipo_activo),
    CONSTRAINT ck_cdt_fechas CHECK (fecha_vencimiento > fecha_emision)
);

-- TES: bonos del Tesoro de Colombia. tasa_cupon es propia del titulo;
-- la tasa a la que cada cliente lo compra queda en la transaccion.
CREATE TABLE tes (
    id_activo         INTEGER       PRIMARY KEY,
    id_tipo_activo    SMALLINT      NOT NULL CHECK (id_tipo_activo = 4),
    serie             VARCHAR(20)   NOT NULL UNIQUE,
    tasa_cupon        NUMERIC(6,4)  NOT NULL CHECK (tasa_cupon > 0 AND tasa_cupon < 1),
    fecha_emision     DATE          NOT NULL,
    fecha_vencimiento DATE          NOT NULL,
    CONSTRAINT fk_tes_activo
        FOREIGN KEY (id_activo, id_tipo_activo)
        REFERENCES activo (id_activo, id_tipo_activo),
    CONSTRAINT ck_tes_fechas CHECK (fecha_vencimiento > fecha_emision)
);

-- ---------------------------------------------------------------------
-- PRECIO_HISTORICO (entidad debil de ACCION_FONDO)              Regla 9
-- Precio de cierre diario en USD cargado desde yfinance.
-- PK compuesta: impide dos precios del mismo activo el mismo dia y su
-- indice sirve para buscar "el precio mas reciente" de un activo.
-- ---------------------------------------------------------------------
CREATE TABLE precio_historico (
    id_activo     INTEGER        NOT NULL REFERENCES accion_fondo (id_activo),
    fecha         DATE           NOT NULL,
    precio_cierre NUMERIC(15,4)  NOT NULL CHECK (precio_cierre > 0),
    PRIMARY KEY (id_activo, fecha)
);

-- ---------------------------------------------------------------------
-- TRM: Tasa Representativa del Mercado (pesos por dolar)
-- Fuente: Superintendencia Financiera - datos.gov.co (dataset 32sa-8pi3)
-- La TRM se publica por rango de vigencia (la del viernes cubre el fin
-- de semana). La restriccion EXCLUDE impide rangos solapados.
-- ---------------------------------------------------------------------
CREATE TABLE trm (
    fecha_desde DATE           PRIMARY KEY,
    fecha_hasta DATE           NOT NULL,
    valor_cop   NUMERIC(10,2)  NOT NULL CHECK (valor_cop > 0),
    CONSTRAINT ck_trm_rango CHECK (fecha_hasta >= fecha_desde),
    CONSTRAINT ex_trm_sin_solape
        EXCLUDE USING gist (daterange(fecha_desde, fecha_hasta, '[]') WITH &&)
);

-- ---------------------------------------------------------------------
-- TRANSACCION: compras y ventas de activos (valores en USD)
--                                             Reglas 4, 5, 6, 7 y 11
-- * monto y comision son columnas GENERADAS: no se pueden escribir a
--   mano, por lo que no hay riesgo de inconsistencia con sus fuentes.
-- * tasa_comision se guarda por transaccion (DEFAULT 0.5 %): si la firma
--   cambia la tarifa, las comisiones historicas no se alteran.
-- * tasa_pactada: tasa efectiva anual fijada en la compra de CDT/TES.
--   Obligatoria solo en esas compras (lo valida el trigger).
-- * Para CDT/TES: cantidad = numero de titulos y precio_unitario = valor
--   invertido por titulo, convertido a USD con la TRM del dia.
-- ---------------------------------------------------------------------
CREATE TABLE transaccion (
    id_transaccion   INTEGER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cuenta        INTEGER        NOT NULL REFERENCES cuenta (id_cuenta),
    id_activo        INTEGER        NOT NULL REFERENCES activo (id_activo),
    tipo_transaccion VARCHAR(10)    NOT NULL
        CHECK (tipo_transaccion IN ('COMPRA', 'VENTA')),
    fecha_hora       TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cantidad         NUMERIC(15,6)  NOT NULL CHECK (cantidad > 0),
    precio_unitario  NUMERIC(15,4)  NOT NULL CHECK (precio_unitario > 0),
    tasa_comision    NUMERIC(6,4)   NOT NULL DEFAULT 0.005
        CHECK (tasa_comision >= 0 AND tasa_comision < 1),
    tasa_pactada     NUMERIC(6,4)
        CHECK (tasa_pactada > 0 AND tasa_pactada < 1),
    monto            NUMERIC(15,2)
        GENERATED ALWAYS AS (ROUND(cantidad * precio_unitario, 2)) STORED,
    comision         NUMERIC(15,2)
        GENERATED ALWAYS AS (ROUND(cantidad * precio_unitario * tasa_comision, 2)) STORED
);

-- ---------------------------------------------------------------------
-- RENDIMIENTO: dividendos e intereses recibidos (USD)           Regla 8
-- ---------------------------------------------------------------------
CREATE TABLE rendimiento (
    id_rendimiento   INTEGER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cuenta        INTEGER        NOT NULL REFERENCES cuenta (id_cuenta),
    id_activo        INTEGER        NOT NULL REFERENCES activo (id_activo),
    fecha            DATE           NOT NULL DEFAULT CURRENT_DATE,
    tipo_rendimiento VARCHAR(10)    NOT NULL
        CHECK (tipo_rendimiento IN ('DIVIDENDO', 'INTERES')),
    monto            NUMERIC(15,2)  NOT NULL CHECK (monto > 0)
);

